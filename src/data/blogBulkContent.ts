function splitMarkdownChunks(input: string) {
  return input
    .split(/\n,\#\s+/)
    .map((part, idx) => (idx === 0 ? part : `# ${part}`))
    .map((s) => s.trim())
    .filter(Boolean);
}

function headingFromMarkdown(markdown: string) {
  const line = markdown.split("\n").find((l) => l.trim().startsWith("# "));
  return line ? line.replace(/^#\s+/, "").trim() : "Blog";
}

function excerptFromMarkdown(markdown: string) {
  const lines = markdown
    .split("\n")
    .map((l) => l.trim())
    .filter((l) => l.length > 0 && !l.startsWith("#") && l !== "---");
  return lines.slice(0, 2).join(" ");
}

export function buildBulkBlogUpdates() {
  const chunks = splitMarkdownChunks(RAW_BLOG_BULK);
  const map: Record<string, BlogBulkUpdate> = {};

  for (let i = 0; i < TARGET_SLUGS.length && i < chunks.length; i += 1) {
    const slug = TARGET_SLUGS[i];
    const markdown = chunks[i];
    map[slug] = {
      title: headingFromMarkdown(markdown),
      excerpt: excerptFromMarkdown(markdown),
      markdown,
    };
  }

  return map;
}

